import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { extname, join, resolve } from 'node:path';
const ROOT = resolve(new URL('..', import.meta.url).pathname);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const srv = createServer(async (req, res) => { try { const p = join(ROOT, 'dist', req.url === '/' ? 'index.html' : decodeURIComponent(req.url.split('?')[0])); const b = await readFile(p); res.writeHead(200, { 'content-type': { '.html': 'text/html', '.js': 'text/javascript', '.webp': 'image/webp', '.png': 'image/png' }[extname(p)] ?? 'application/octet-stream' }); res.end(b); } catch { res.writeHead(404); res.end(); } });
await new Promise((r) => srv.listen(0, r));
const url = `http://localhost:${srv.address().port}/`;
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 664 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
await ctx.addInitScript(() => { window.__BD_TEST = { noTutorial: true }; });
const page = await ctx.newPage();
const ev = (f, a) => page.evaluate(f, a);
await page.goto(url); await page.waitForFunction(() => window.__BD?.ui()?.panel);
await ev(readFileSync(join(ROOT, 'tools', 'midsave.js'), 'utf8')); await ev(() => window.__midSave());
await page.reload(); await page.waitForFunction(() => window.__BD?.ui()?.panel); await sleep(1500);
const reset = () => ev(() => { const u = __BD.ui(); u.closeModal(true); u.closeScreen(); u.closePanel(true); });
const shot = async (n) => { await sleep(900); await page.screenshot({ path: `screens/stage9c-${n}.png` }); console.log('shot', n, JSON.stringify(await ev(() => __BD.layoutIssues()))); };
await reset(); await shot('hud-base');
await ev(() => { const st = __BD.store; st.state.resources.energy = 1e6; st.train('bearer', 5); try { st.train('voyager', 3); } catch {} __BD.ui().openScreen('troops'); }); await shot('barracks-training');
await reset(); await ev(() => __BD.ui().openScreen('squads')); await shot('squads');
await reset(); await ev(() => __BD.ui().openScreen('infirmary')); await shot('infirmary');
await reset(); await ev(() => __BD.ui().openScreen('armory')); await shot('armory');
await browser.close(); srv.close();
